#!/usr/bin/env python3
"""
Diff-based style learning, ported from the pattern documented in
~/Claude/playbooks/editorial/blog-generation-pipeline.md (built and proven
on a different project's blog-generation pipeline, adapted here for TBV's
actual shape: no database, no admin UI -- content lives in git, and an
"edit" is just a later commit to the same file).

WHAT THIS IS FOR: once a native speaker validates a translated page (or an
editor tightens the English on a page), the edit they made is signal. This
script diffs the ORIGINAL (AI-generated, unvalidated) version of a file
against a LATER version -- typically HEAD after someone has edited it -- and
extracts word/phrase-level differences: what got removed (disfavored) and
what got added (favored). Patterns that recur across multiple edits (not
one-off phrasing) get written into EDITORIAL_LEARNED_PATTERNS.md, which
future content-generation prompts (for this site or any subagent translating
new pages) should read alongside EDITORIAL_STYLE_GUIDE.md before writing.

Two-file split (do not merge these, see the playbook doc for why):
- EDITORIAL_STYLE_GUIDE.md   -- hand-written, human-owned, standing rules.
                                 This script never touches it.
- EDITORIAL_LEARNED_PATTERNS.md -- machine-owned, fully regenerated by this
                                 script every run from the accumulated diff
                                 history. Never hand-edit this file; edits
                                 will be silently discarded on the next run.

USAGE:
    # Diff a file's first commit against its current (HEAD) version --
    # the common case once a validator has edited a page in place:
    python3 build/learn_from_edits.py content/es/scams/phishing.md

    # Diff two specific commits (e.g. the commit right before validation
    # vs. the commit that validated it):
    python3 build/learn_from_edits.py content/es/scams/phishing.md \\
        --from abc1234 --to def5678

    # Re-run across every content file that has more than one commit
    # (regenerates EDITORIAL_LEARNED_PATTERNS.md from scratch):
    python3 build/learn_from_edits.py --all

This only extracts a pattern when it repeats (occurrences >= 2 across all
diffs analyzed) -- a single edit is noise; a pattern the same editor makes
twice is signal. See analyzeEditDiff in the ported pattern for the same
threshold used on the source project.
"""
import os, re, sys, json, subprocess, argparse, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEARNED_FILE = os.path.join(ROOT, "EDITORIAL_LEARNED_PATTERNS.md")
STATE_FILE = os.path.join(ROOT, "build", ".editorial_learned_state.json")


def git(*args):
    return subprocess.run(["git", "-C", ROOT] + list(args), capture_output=True, text=True, check=True).stdout


def file_commits(path):
    out = git("log", "--format=%H", "--follow", "--", path)
    commits = [c for c in out.strip().split("\n") if c]
    return list(reversed(commits))  # oldest first


def show_at(path, commit):
    try:
        return git("show", "%s:%s" % (commit, path))
    except subprocess.CalledProcessError:
        return None


def strip_frontmatter_and_banner(text):
    # Only the actual prose should feed the learner -- frontmatter fields
    # and the unvalidated-translation banner are structural, not editorial.
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            text = text[end + 4:]
    text = re.sub(r"^>.*$", "", text, flags=re.M)
    return text.strip()


def word_diff(before, after):
    # Word-level diff (not line-level): translation/copy edits are often
    # a few words inside a sentence, and a line-level diff would treat the
    # whole line as changed, burying the actual signal. Uses difflib's
    # SequenceMatcher on a word tokenization.
    import difflib
    before_words = re.findall(r"\S+", before)
    after_words = re.findall(r"\S+", after)
    sm = difflib.SequenceMatcher(None, before_words, after_words, autojunk=False)
    removed, added = [], []
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag in ("delete", "replace"):
            chunk = " ".join(before_words[i1:i2]).strip()
            if chunk:
                removed.append(chunk)
        if tag in ("insert", "replace"):
            chunk = " ".join(after_words[j1:j2]).strip()
            if chunk:
                added.append(chunk)
    return removed, added


def lang_for(path):
    rel = os.path.relpath(path, ROOT)
    parts = rel.split(os.sep)
    if len(parts) >= 2 and parts[0] == "content":
        code = parts[1]
        return code if len(code) <= 3 and code.isalpha() else "en"
    return "en"


def analyze_pair(path, before_text, after_text, state):
    before = strip_frontmatter_and_banner(before_text)
    after = strip_frontmatter_and_banner(after_text)
    if before == after:
        return
    removed, added = word_diff(before, after)
    lang = lang_for(path)
    bucket = state.setdefault(lang, {"disfavored": {}, "favored": {}, "posts_analyzed": 0})
    bucket["posts_analyzed"] += 1
    # Only phrases with real content (skip single-punctuation noise), and
    # cap length so this captures phrase-level patterns, not whole
    # rewritten paragraphs (which aren't a reusable "pattern").
    for chunk in removed:
        words = chunk.split()
        if 1 <= len(words) <= 8 and any(c.isalpha() for c in chunk):
            bucket["disfavored"][chunk] = bucket["disfavored"].get(chunk, 0) + 1
    for chunk in added:
        words = chunk.split()
        if 1 <= len(words) <= 8 and any(c.isalpha() for c in chunk):
            bucket["favored"][chunk] = bucket["favored"].get(chunk, 0) + 1

    # Structural / tone heuristics, same thresholds as the ported pattern.
    before_wc, after_wc = len(before.split()), len(after.split())
    if before_wc and abs(after_wc - before_wc) / before_wc > 0.20:
        bucket.setdefault("structural_notes", []).append(
            "%s: word count changed %d -> %d (>20%%)" % (os.path.relpath(path, ROOT), before_wc, after_wc)
        )


def render(state):
    lines = [
        "# Editorial learned patterns",
        "",
        "**Machine-owned. Regenerated by `build/learn_from_edits.py` on every",
        "run -- do not hand-edit this file, changes will be discarded.** Add",
        "standing rules to `EDITORIAL_STYLE_GUIDE.md` instead (hand-written,",
        "never touched by this script).",
        "",
        "Patterns only appear here once they recur (2+ occurrences across",
        "analyzed edits) -- a single edit is noise, a repeated one is signal.",
        "Generated: run `python3 build/learn_from_edits.py --all` to refresh.",
        "",
    ]
    if not any(b.get("posts_analyzed") for b in state.values()):
        lines.append("_No validated edits analyzed yet. This file activates the moment_")
        lines.append("_a native-speaker validation pass edits a translated page, or an_")
        lines.append("_editor tightens English copy after the fact -- see BACKLOG.md._")
        return "\n".join(lines) + "\n"

    for lang in sorted(state.keys()):
        bucket = state[lang]
        if not bucket.get("posts_analyzed"):
            continue
        favored = sorted(bucket["favored"].items(), key=lambda kv: -kv[1])
        disfavored = sorted(bucket["disfavored"].items(), key=lambda kv: -kv[1])
        recurring_favored = [(p, n) for p, n in favored if n >= 2]
        recurring_disfavored = [(p, n) for p, n in disfavored if n >= 2]
        structural = bucket.get("structural_notes", [])
        # Skip languages where nothing recurred and nothing structural
        # happened -- most of the 45 languages currently have exactly one
        # historical commit pair (the tagline-update pass or similar), which
        # isn't a reusable editorial lesson, just noise in this report.
        if not recurring_favored and not recurring_disfavored and not structural:
            continue
        lines.append("## %s (%d edit%s analyzed)" % (
            lang, bucket["posts_analyzed"], "" if bucket["posts_analyzed"] == 1 else "s"))
        lines.append("")
        if recurring_favored:
            lines.append("**Favored** (editors added these more than once):")
            for phrase, n in recurring_favored[:20]:
                lines.append('- "%s" (×%d)' % (phrase, n))
            lines.append("")
        if recurring_disfavored:
            lines.append("**Disfavored** (editors removed these more than once):")
            for phrase, n in recurring_disfavored[:20]:
                lines.append('- "%s" (×%d)' % (phrase, n))
            lines.append("")
        for note in bucket.get("structural_notes", [])[:10]:
            lines.append("- Structural: %s" % note)
        lines.append("")
    return "\n".join(lines) + "\n"


def load_state():
    if os.path.exists(STATE_FILE):
        return json.load(open(STATE_FILE, encoding="utf-8"))
    return {}


def save_state(state):
    json.dump(state, open(STATE_FILE, "w", encoding="utf-8"), indent=2, ensure_ascii=False)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("path", nargs="?")
    ap.add_argument("--from", dest="from_ref")
    ap.add_argument("--to", dest="to_ref", default="HEAD")
    ap.add_argument("--all", action="store_true",
                     help="Re-scan every content file's full commit history "
                          "(rebuilds state from scratch -- doesn't merge with "
                          "prior single-file runs, since --all is already the "
                          "complete picture)")
    args = ap.parse_args()

    # Single-file runs ACCUMULATE into persisted state (build/.editorial_
    # learned_state.json, gitignored -- EDITORIAL_LEARNED_PATTERNS.md is the
    # committed, human-facing output) so validating page A on Monday and
    # page B on Tuesday both end up reflected. --all always rebuilds from
    # scratch since it's re-deriving the complete picture from git history
    # anyway, not adding to a partial one.
    state = {} if args.all else load_state()

    if args.all:
        out = git("ls-files", "content/")
        paths = [p for p in out.strip().split("\n") if p.endswith(".md")]
        for rel in paths:
            abspath = os.path.join(ROOT, rel)
            commits = file_commits(rel)
            if len(commits) < 2:
                continue
            first_text = show_at(rel, commits[0])
            last_text = show_at(rel, commits[-1])
            if first_text is not None and last_text is not None:
                analyze_pair(abspath, first_text, last_text, state)
    elif args.path:
        rel = os.path.relpath(args.path, ROOT)
        from_ref = args.from_ref
        if not from_ref:
            commits = file_commits(rel)
            if not commits:
                print("No git history for %s" % rel)
                sys.exit(1)
            from_ref = commits[0]
        before_text = show_at(rel, from_ref)
        after_text = show_at(rel, args.to_ref) if args.to_ref != "HEAD" else open(args.path, encoding="utf-8").read()
        if before_text is None:
            print("Could not read %s at %s" % (rel, from_ref))
            sys.exit(1)
        analyze_pair(args.path, before_text, after_text, state)
    else:
        ap.print_help()
        sys.exit(1)

    save_state(state)
    open(LEARNED_FILE, "w", encoding="utf-8").write(render(state))
    print("wrote %s" % LEARNED_FILE)
